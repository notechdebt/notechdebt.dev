// Generates the static pages that sit next to the hand-written index.html:
//   work/index.html, work/<slug>/index.html, 404.html and sitemap.xml.
// The header, contact block and footer are copied from index.html (between the
// <!-- shared:... --> markers), so edit them there and rerun:  node tools/build.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { projects, LAYERS } from './projects.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://notechdebt.dev';
const index = readFileSync(join(ROOT, 'index.html'), 'utf8');

function shared(name) {
  const m = index.match(new RegExp(`<!-- shared:${name}(?:\\s[^>]*)?-->\\n?([\\s\\S]*?)<!-- /shared:${name} -->`));
  if (!m) throw new Error(`index.html is missing the <!-- shared:${name} --> block`);
  return m[1].trimEnd();
}
const HEAD = shared('head'), HEADER = shared('header'), CONTACT = shared('contact'), FOOTER = shared('footer');

const esc = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const host = (u) => u.replace(/^https?:\/\//, '').replace(/\/$/, '');
const ld = (o) => `<script type="application/ld+json">\n${JSON.stringify(o, null, 2).replace(/</g, '\\u003c')}\n</script>`;

function img(slug, [w, h], alt, sizes, extra = '') {
  return `<img src="/img/${slug}-640.webp" srcset="/img/${slug}-640.webp 640w, /img/${slug}-960.webp 960w, /img/${slug}.webp 1280w" sizes="${sizes}" width="${w}" height="${h}" alt="${esc(alt)}"${extra}>`;
}

// The day a page first went into git, so its publish date stays put across rebuilds; today for a new page.
function published(rel) {
  try {
    const first = execFileSync('git', ['log', '--diff-filter=A', '--format=%cs', '--', rel], { cwd: ROOT, encoding: 'utf8' }).trim().split('\n').pop();
    if (first) return first;
  } catch {}
  return new Date().toLocaleDateString('en-CA');
}

