// ---------- sitemap: lastmod is the last commit that touched a page's sources, or today if they have uncommitted changes ----------
// (the generated pages aren't committed; GitHub Actions builds them on every push, with full git history)
const today = new Date().toLocaleDateString('en-CA'); // YYYY-MM-DD in local time
function lastmod(sources) {
  try {
    const dirty = execFileSync('git', ['status', '--porcelain', '--', ...sources], { cwd: ROOT, encoding: 'utf8' }).trim();
    if (dirty) return today;
    return execFileSync('git', ['log', '-1', '--format=%cs', '--', ...sources], { cwd: ROOT, encoding: 'utf8' }).trim() || today;
  } catch { return today; }
}
const PAGE_SOURCES = ['tools/projects.mjs', 'tools/build.mjs'];
const urls = [['/', ['index.html']], [WORK.path, PAGE_SOURCES], ...projects.map((p) => [`/work/${p.slug}/`, PAGE_SOURCES]), ...appPages.map((pg) => [`/apps/${pg.slug}/`, ['tools/apps.mjs', 'tools/build.mjs']])];
writeFileSync(join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(([u, f]) => `  <url><loc>${SITE}${u}</loc><lastmod>${lastmod(f)}</lastmod></url>`).join('\n')}
</urlset>
`);
out.push('sitemap.xml');

// ---------- cache-busting (CI only): point every page at the CSS/JS by content hash, so a deploy is never
// shown with a stale stylesheet. Run as `node tools/build.mjs --stamp`; it rewrites index.html, so not locally. ----------
if (process.argv.includes('--stamp')) {
  const hash = (f) => createHash('sha256').update(readFileSync(join(ROOT, f))).digest('hex').slice(0, 10);
  const stamps = [['/assets/site.css', hash('assets/site.css')], ['/assets/site.js', hash('assets/site.js')]];
  for (const rel of ['index.html', ...out.filter((f) => f.endsWith('.html'))]) {
    const file = join(ROOT, rel);
    let html = readFileSync(file, 'utf8');
    for (const [url, h] of stamps) html = html.split(`"${url}"`).join(`"${url}?v=${h}"`);
    writeFileSync(file, html);
  }
  console.log(`Stamped CSS/JS versions: ${stamps.map(([u, h]) => `${u}?v=${h}`).join(', ')}`);
}

