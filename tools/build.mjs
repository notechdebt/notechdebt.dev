function breadcrumb(path, items) {
  return {
    '@type': 'BreadcrumbList', '@id': SITE + path + '#breadcrumb',
    itemListElement: items.map(([name, p], i) => ({ '@type': 'ListItem', position: i + 1, name, ...(p ? { item: SITE + p } : {}) }))
  };
}

